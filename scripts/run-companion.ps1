param(
    [Parameter(Mandatory=$true)][string]$ServerDll,
    [Parameter(Mandatory=$true)][string]$ClientDll,
    [switch]$EnableDesktopActions
)
$ErrorActionPreference = 'Stop'
if ([Environment]::OSVersion.Platform -ne [PlatformID]::Win32NT) {
    throw 'The graphical companion launcher requires Windows.'
}
if (-not (Test-Path -LiteralPath $ServerDll) -or -not (Test-Path -LiteralPath $ClientDll)) {
    throw 'Application files are missing. Build the source or re-extract the complete preview package.'
}
$probe = New-Object System.Net.Sockets.TcpClient
$occupied = $false
try { $probe.Connect('127.0.0.1', 32178); $occupied = $true } catch { } finally { $probe.Dispose() }
if ($occupied) { throw 'Port 32178 is in use. Close the existing bridge before using this launcher.' }

$previousPolicy = $env:ALEXA_ALLOW_DESKTOP_ACTIONS
$server = $null
$ownedReady = $false
try {
    $env:ALEXA_ALLOW_DESKTOP_ACTIONS = if ($EnableDesktopActions) { '1' } else { '0' }
    # The token is generated by the bridge, never passed through command-line arguments.
    $server = Start-Process -FilePath 'dotnet' -ArgumentList ('"{0}"' -f $ServerDll) -WorkingDirectory (Split-Path -Parent $ServerDll) -PassThru
    $deadline = [DateTime]::UtcNow.AddSeconds(30)
    while ([DateTime]::UtcNow -lt $deadline) {
        $server.Refresh()
        if ($server.HasExited) { throw "Bridge exited before startup (code $($server.ExitCode))." }
        try {
            $health = Invoke-RestMethod -Uri 'http://127.0.0.1:32178/health' -TimeoutSec 1
            if ($health.processId -eq $server.Id) { $ownedReady = $true; break }
        } catch { }
        Start-Sleep -Milliseconds 250
    }
    if (-not $ownedReady) { throw 'This bridge did not become ready within 30 seconds.' }
    Write-Host 'Bridge started in its own console. Keep it open for per-request approvals.'
    & dotnet $ClientDll
    if ($LASTEXITCODE -ne 0) { throw "Simulator exited with code $LASTEXITCODE." }
} finally {
    if ($null -ne $server) {
        $server.Refresh()
        if (-not $server.HasExited -and $ownedReady) {
            try {
                $runtime = $env:ALEXA_BRIDGE_RUNTIME_DIR
                if ([string]::IsNullOrWhiteSpace($runtime)) {
                    $runtime = Join-Path ([Environment]::GetFolderPath('LocalApplicationData')) 'AlexaKeyboardBridge/runtime'
                }
                $token = (Get-Content -LiteralPath (Join-Path $runtime 'mcp-auth-token') -Raw).Trim()
                $headers = @{ Authorization = "Bearer $token" }
                Invoke-RestMethod -Method Post -Uri 'http://127.0.0.1:32178/local/shutdown' -Headers $headers -TimeoutSec 3 | Out-Null
            } catch { Write-Warning 'Graceful bridge shutdown was unavailable; stopping only this launcher-owned process.' }
        }
        if (-not $server.WaitForExit(5000)) { $server.Kill(); $server.WaitForExit() }
        $server.Dispose()
    }
    $env:ALEXA_ALLOW_DESKTOP_ACTIONS = $previousPolicy
}
